#!/usr/bin/env python3
"""LASH - Adaptive Semantic Hybridization for black-box jailbreaking.

Faithful paper-local reimplementation of Nafi et al., "LASH: Adaptive Semantic
Hybridization for Black-Box Jailbreaking of Large Language Models" (arXiv
2605.21362, 2026). No official code repository was found (arXiv source ships
LaTeX only; the Awesome-Jailbreak-on-LLMs index lists the paper without a code
link), so this is a clean reimplementation with explicit provenance.

Mechanism (one sentence): for each harmful request, build a pool of weak seed
prompts from several black-box base attacks, then run a genetic algorithm that
searches over seed *subsets* and softmax *mixture weights*, asking a composition
LLM to synthesize one natural-language candidate per genome and scoring it with a
two-stage (keyword refusal -> LLM judge) fitness function.

Pipeline per request x:
  1. SEED POOL  B(x) = {PAIR-style, TAP-style, AutoDAN-Turbo-style} seed prompts,
     each produced by a few attacker-LLM queries (reduced budget, intentionally
     weak; paper: 5/5/10 target queries). See SEED FIDELITY note below.
  2. SUBSET SEARCH  enumerate nonempty subsets of B(x) in DESCENDING size.
  3. GA over logits  per subset: P genomes z~N(0,1), softmax->weights, compose,
     query target, score; keep elites (TopK), mutate elites with N(0,sigma^2).
  4. COMPOSITION  M(x, {(b_i,w_i)}) -> one candidate prompt (verbatim sys prompt).
  5. TWO-STAGE FITNESS  refusal keyword -> 0; else JudgeLLM rating in [0,10].
  6. EARLY STOP  when score >= tau (default 9) or query budget exhausted.

Algorithm 1 (alg:lash_ga) is implemented verbatim. Composition + judge system
prompts are copied verbatim from Figures comp-sys-prompt / judge-sys-prompt.

Roles (each its own --max-tokens):
  --target-model     deepseek/deepseek-v4-flash   (reasoning target)
  --judge-model      qwen-2.5-7b-instruct          (cheap, fast, non-reasoning)
  --attacker-model   mythomax-l2-13b               (weak-aligned seed gen)
  --composition-model qwen-2.5-7b-instruct          (cheap, fast, non-reasoning)

SEED FIDELITY: the paper draws seeds from full PAIR / TAP / AutoDAN-Turbo runs.
Re-vendoring three whole attack frameworks would dwarf LASH's actual
contribution, so seeds here are generated by faithful *lightweight* black-box
variants of each family (an attacker LLM driven by each method's signature
strategy, under the paper's reduced query budgets). LASH's novel mechanism --
subset enumeration, softmax-weighted semantic composition, GA over mixture
logits, two-stage fitness -- is implemented exactly. The reduced seed generators
are the one fidelity gap; record as such.

Env: OPENROUTER_API_KEY (walk-up .env lookup finds the global XSkillForge/.env;
base https://openrouter.ai/api/v1).
Run:  $PY scripts/attack.py --sample 10   (PY = shared XSkillForge/.venv interpreter)
"""
