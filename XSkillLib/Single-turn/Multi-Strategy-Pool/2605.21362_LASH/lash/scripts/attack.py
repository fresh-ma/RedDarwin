class ChatClient:
    def __init__(self, max_retries: int = 4, timeout: float = 120.0) -> None:
        from openai import OpenAI

        api_key = os.environ.get("OPENROUTER_API_KEY")
        if not api_key:
            raise RuntimeError(
                "OPENROUTER_API_KEY not set (method-local .env or shell env). "
                "See .env.example."
            )
        self._client = OpenAI(base_url=OPENROUTER_BASE_URL, api_key=api_key, timeout=timeout)
        self.max_retries = max_retries
        self.calls = 0  # total provider calls (any role)

    def chat(
        self,
        model: str,
        messages: list[dict[str, str]],
        max_tokens: int,
        temperature: float = 0.0,
        top_p: float = 1.0,
    ) -> str:
        """Return assistant text. Raises on persistent provider failure.

        For reasoning models (e.g. deepseek-v4-flash) an empty content with
        finish_reason='length' means max_tokens is too low -> raise so the caller
        bumps the cap, NOT a refusal and NOT 'model unavailable'.
        """
        last_err: Exception | None = None
        for attempt in range(self.max_retries):
            try:
                self.calls += 1
                resp = self._client.chat.completions.create(
                    model=model,
                    messages=messages,
                    max_tokens=max_tokens,
                    temperature=temperature,
                    top_p=top_p,
                )
                choice = resp.choices[0]
                content = choice.message.content if choice.message else None
                finish = getattr(choice, "finish_reason", None)
                if content is None or content.strip() == "":
                    if finish == "length":
                        raise RuntimeError(
                            f"empty content with finish_reason=length for {model}; "
                            f"max_tokens={max_tokens} too low (reasoning model burned "
                            f"the budget on hidden reasoning) -- raise the cap."
                        )
                    # transient empty -> retry
                    raise RuntimeError(f"empty content (finish_reason={finish}) for {model}")
                return content
            except Exception as e:  # noqa: BLE001 - surface after retries
                last_err = e
                msg = str(e).lower()
                # do not retry the cap-too-low signal
                if "too low" in msg:
                    raise
                if attempt < self.max_retries - 1:
                    time.sleep(2.0 * (attempt + 1))
        raise RuntimeError(f"provider call failed for {model}: {last_err}")


