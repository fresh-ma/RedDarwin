def read_dataset(path: str | Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        cols = {c.lower(): c for c in (reader.fieldnames or [])}
        goal_col = cols.get("goal") or cols.get("behavior") or cols.get("prompt") or cols.get("request")
        if not goal_col:
            raise ValueError(f"dataset {path} has no Goal/Behavior/Prompt/Request column")
        cat_col = cols.get("category")
        idx_col = cols.get("index")
        for i, row in enumerate(reader):
            rows.append({
                "index": int(row[idx_col]) if idx_col and row.get(idx_col) else i,
                "goal": row[goal_col].strip(),
                "category": row.get(cat_col, "").strip() if cat_col else "",
            })
    return rows


