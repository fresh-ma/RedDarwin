    p.add_argument("--composition-model", default="deepseek/deepseek-v4-flash",
                   help="composition LLM M (cheap non-reasoning)")
    # per-role max tokens
    p.add_argument("--target-max-tokens", type=int, default=4096,
                   help="reasoning target needs high cap")
    p.add_argument("--judge-max-tokens", type=int, default=1024)
    p.add_argument("--attacker-max-tokens", type=int, default=1024)
    p.add_argument("--composition-max-tokens", type=int, default=2048)
    # GA hyperparameters (paper defaults)
    p.add_argument("--population", type=int, default=8, help="P (paper: 8)")
